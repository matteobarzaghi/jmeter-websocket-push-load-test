#!/usr/bin/env bash
#
# jmeter_injector_tuning.sh
# Idempotent provisioning for JMeter injector VMs — Push Terminals System
#
# Applies the OS tuning needed to sustain thousands of long-lived outbound
# WebSocket connections from a JMeter injector (file descriptors, ephemeral
# ports, TIME_WAIT, conntrack, socket buffers), then checks the applied values
# and prints a pre-test report.
#
# Does NOT touch the target hosts/infrastructure: it only acts on the operating
# system of the local VM it runs on.
#
# Usage:
#   sudo ./jmeter_injector_tuning.sh            # apply the tuning + report
#   sudo ./jmeter_injector_tuning.sh --check     # report only, changes nothing
#   sudo ./jmeter_injector_tuning.sh --dry-run   # print what it would do, does not apply
#
# Idempotent: safe to re-run with no side effects, the config files are
# overwritten with the same content computed from the VM RAM.

set -euo pipefail

MODE="apply"
for arg in "$@"; do
  case "$arg" in
    --check) MODE="check" ;;
    --dry-run) MODE="dry-run" ;;
    -h|--help)
      grep '^#' "$0" | sed 's/^#//'
      exit 0
      ;;
  esac
done

SYSCTL_FILE="/etc/sysctl.d/99-loadtest.conf"
LIMITS_FILE="/etc/security/limits.d/99-jmeter.conf"
JMETER_USER="${JMETER_USER:-$(logname 2>/dev/null || echo '*')}"

log()  { echo "[jmeter-tuning] $*"; }
warn() { echo "[jmeter-tuning][WARNING] $*" >&2; }

if [[ "$MODE" != "check" && $EUID -ne 0 ]]; then
  warn "Root privileges are required to apply the tuning (sysctl / limits.d)."
  warn "Re-run with: sudo $0 $*"
  exit 1
fi

# ---------------------------------------------------------------------------
# 1. Sizing based on the VM RAM
# ---------------------------------------------------------------------------
RAM_KB=$(awk '/MemTotal/ {print $2}' /proc/meminfo)
RAM_GB=$(( RAM_KB / 1024 / 1024 ))
if [[ $RAM_GB -lt 1 ]]; then RAM_GB=1; fi

# tcp_mem: max = ~1/3 of total RAM (in 4KB pages), pressure = 2/3 of max, min = 1/2 of max
TCP_MEM_MAX_PAGES=$(( RAM_KB * 1024 / 3 / 4096 ))
TCP_MEM_PRESSURE_PAGES=$(( TCP_MEM_MAX_PAGES * 2 / 3 ))
TCP_MEM_MIN_PAGES=$(( TCP_MEM_MAX_PAGES / 2 ))

# Suggested JVM heap: max 8g or half of the VM RAM, whichever is lower
SUGGESTED_XMX_GB=$(( RAM_GB / 2 ))
if [[ $SUGGESTED_XMX_GB -gt 8 ]]; then SUGGESTED_XMX_GB=8; fi
if [[ $SUGGESTED_XMX_GB -lt 1 ]]; then SUGGESTED_XMX_GB=1; fi

log "Detected RAM: ${RAM_GB} GB"
log "tcp_mem (4KB pages) -> min=${TCP_MEM_MIN_PAGES} pressure=${TCP_MEM_PRESSURE_PAGES} max=${TCP_MEM_MAX_PAGES}"

# ---------------------------------------------------------------------------
# 2. Target content of the config files
# ---------------------------------------------------------------------------
read -r -d '' SYSCTL_CONTENT <<EOF || true
# Generated by jmeter_injector_tuning.sh — do not edit by hand, re-run the script.
# Target: JMeter injector with thousands of long-lived WebSocket connections.

# ---------- File descriptors ----------
fs.file-max = 2097152
fs.nr_open  = 2097152

# ---------- Ephemeral ports / TIME_WAIT ----------
net.ipv4.ip_local_port_range = 1024 65535
net.ipv4.tcp_tw_reuse        = 1
net.ipv4.tcp_fin_timeout     = 15
net.ipv4.tcp_max_tw_buckets  = 2000000

# ---------- Backlog and queues ----------
net.core.somaxconn             = 65535
net.ipv4.tcp_max_syn_backlog   = 65535
net.core.netdev_max_backlog    = 250000
net.ipv4.tcp_abort_on_overflow = 0

# ---------- Socket buffers (do NOT raise the defaults: they multiply by N connections) ----------
net.core.rmem_max            = 16777216
net.core.wmem_max            = 16777216
net.core.rmem_default        = 262144
net.core.wmem_default        = 262144
net.ipv4.tcp_rmem            = 4096 16384 16777216
net.ipv4.tcp_wmem            = 4096 16384 16777216
net.ipv4.tcp_mem             = ${TCP_MEM_MIN_PAGES} ${TCP_MEM_PRESSURE_PAGES} ${TCP_MEM_MAX_PAGES}
net.ipv4.tcp_moderate_rcvbuf = 1

# ---------- Keepalive: WSS connections idle between pushes ----------
net.ipv4.tcp_keepalive_time   = 300
net.ipv4.tcp_keepalive_intvl  = 30
net.ipv4.tcp_keepalive_probes = 5

# ---------- Connection behaviour ----------
net.ipv4.tcp_slow_start_after_idle = 0
net.ipv4.tcp_no_metrics_save       = 1
net.ipv4.tcp_syncookies             = 1
net.ipv4.tcp_synack_retries         = 3
net.ipv4.tcp_syn_retries            = 3

# ---------- Threads and processes ----------
kernel.pid_max     = 4194304
kernel.threads-max = 4194304
vm.max_map_count   = 1048576

# ---------- Memory ----------
vm.swappiness        = 1
vm.overcommit_memory = 1
EOF

read -r -d '' LIMITS_CONTENT <<EOF || true
# Generated by jmeter_injector_tuning.sh — do not edit by hand, re-run the script.
*    soft  nofile  1048576
*    hard  nofile  1048576
root soft  nofile  1048576
root hard  nofile  1048576
${JMETER_USER} soft nofile 1048576
${JMETER_USER} hard nofile 1048576
*    soft  nproc   unlimited
*    hard  nproc   unlimited
EOF

# ---------------------------------------------------------------------------
# 3. Apply (or show, in dry-run)
# ---------------------------------------------------------------------------
if [[ "$MODE" == "apply" ]]; then
  log "Writing ${SYSCTL_FILE}"
  echo "$SYSCTL_CONTENT" > "$SYSCTL_FILE"

  log "Writing ${LIMITS_FILE} (user: ${JMETER_USER})"
  echo "$LIMITS_CONTENT" > "$LIMITS_FILE"

  log "Applying sysctl --system"
  sysctl --system > /dev/null

  # conntrack: tune only if the module is actually loaded
  if lsmod 2>/dev/null | grep -q '^nf_conntrack'; then
    warn "nf_conntrack is loaded: it can saturate well before the target connections."
    log "Applying conntrack tuning"
    {
      echo "net.netfilter.nf_conntrack_max = 1048576"
      echo "net.netfilter.nf_conntrack_tcp_timeout_established = 1200"
      echo "net.netfilter.nf_conntrack_buckets = 262144"
    } >> "$SYSCTL_FILE"
    sysctl -p "$SYSCTL_FILE" > /dev/null || true
    if [[ -w /sys/module/nf_conntrack/parameters/hashsize ]]; then
      echo 262144 > /sys/module/nf_conntrack/parameters/hashsize
    fi
  else
    log "nf_conntrack not loaded: no action needed (one less potential bottleneck)."
  fi

elif [[ "$MODE" == "dry-run" ]]; then
  echo "--- ${SYSCTL_FILE} (content that would be written) ---"
  echo "$SYSCTL_CONTENT"
  echo "--- ${LIMITS_FILE} (content that would be written) ---"
  echo "$LIMITS_CONTENT"
fi

# ---------------------------------------------------------------------------
# 4. PAM check (not changed automatically: only reported)
# ---------------------------------------------------------------------------
for pamfile in /etc/pam.d/sshd /etc/pam.d/login; do
  if [[ -f "$pamfile" ]] && ! grep -q pam_limits.so "$pamfile"; then
    warn "$pamfile does not include pam_limits.so — the limits.d limits will NOT apply to SSH sessions."
    warn "Add manually: session required pam_limits.so"
  fi
done

# ---------------------------------------------------------------------------
# 5. Pre-test report
# ---------------------------------------------------------------------------
echo ""
echo "==================== PRE-TEST REPORT ===================="
echo "VM RAM:                     ${RAM_GB} GB"
echo "fs.nr_open:                 $(cat /proc/sys/fs/nr_open 2>/dev/null || echo '?')"
echo "fs.file-max:                $(cat /proc/sys/fs/file-max 2>/dev/null || echo '?')"
echo "ip_local_port_range:        $(cat /proc/sys/net/ipv4/ip_local_port_range 2>/dev/null || echo '?')"
echo "tcp_tw_reuse:                $(cat /proc/sys/net/ipv4/tcp_tw_reuse 2>/dev/null || echo '?')"
echo "tcp_fin_timeout:            $(cat /proc/sys/net/ipv4/tcp_fin_timeout 2>/dev/null || echo '?')"
echo "ulimit -Hn (current shell): $(ulimit -Hn 2>/dev/null || echo '?')  (expected 1048576 — needs a new session after the first run)"
if lsmod 2>/dev/null | grep -q '^nf_conntrack'; then
  echo "conntrack:                  LOADED -> max=$(cat /proc/sys/net/netfilter/nf_conntrack_max 2>/dev/null || echo '?') count=$(cat /proc/sys/net/netfilter/nf_conntrack_count 2>/dev/null || echo '?')"
else
  echo "conntrack:                  not loaded (OK)"
fi
echo "-----------------------------------------------------------"
echo "Available ephemeral ports: ~64,512 (range 1024-65535)"
echo "Realistic WS connections for THIS JVM (JMeter thread-per-VU limit, not a system limit): 2,000-5,000"
echo "Suggested JVM_ARGS (bin/jmeter or JVM_ARGS environment variable):"
echo "  -Xms${SUGGESTED_XMX_GB}g -Xmx${SUGGESTED_XMX_GB}g -Xss256k -XX:+UseG1GC -XX:MaxGCPauseMillis=200 \\"
echo "  -XX:+ParallelRefProcEnabled -XX:MaxMetaspaceSize=512m \\"
echo "  -Djava.net.preferIPv4Stack=true -Dsun.net.inetaddr.ttl=0"
echo "============================================================"
echo ""
log "If this was the first run: close and reopen the SSH session before starting JMeter,"
log "otherwise ulimit -n will keep showing the old value for the current shell."
log "Remember: always run in non-GUI mode (jmeter -n -t plan.jmx -l results.jtl)."
